import { readFile, writeFile, mkdir, copyFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { dirname, resolve, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
const root = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const at = args.indexOf('--web-root');
if (at < 0 || !args[at + 1]) throw new Error('Pass --web-root with the consumer build toolchain.');
const web = resolve(args[at + 1]);
const sha = (bytes) => createHash('sha256').update(bytes).digest('hex');
async function walk(path) {
  const entries = await readdir(path, { withFileTypes: true });
  return (
    await Promise.all(
      entries.map((entry) =>
        entry.isDirectory() ? walk(join(path, entry.name)) : [join(path, entry.name)],
      ),
    )
  ).flat();
}
const assets = join(root, 'assets');
await mkdir(join(assets, 'cpp'), { recursive: true });
await mkdir(join(assets, 'ort'), { recursive: true });
await mkdir(join(assets, 'models'), { recursive: true });
await mkdir(join(root, 'licenses'), { recursive: true });
const cppPath = JSON.parse(await readFile(join(web, 'vendor/docscan-native.json'), 'utf8')).base;
if (!cppPath) throw new Error('Build native WASM first.');
for (const file of ['docscan.wasm', 'docscan.mjs', 'build.json'])
  await copyFile(join(web, 'public', cppPath, file), join(assets, 'cpp', file));
const require = createRequire(join(web, 'package.json'));
const ort = resolve(dirname(require.resolve('onnxruntime-web/wasm')), '..');
for (const file of ['ort-wasm-simd-threaded.wasm', 'ort-wasm-simd-threaded.mjs'])
  await copyFile(join(ort, 'dist', file), join(assets, 'ort', file));
for (const file of ['gcnet-2eb69a0a.onnx', 'document-defects.onnx'])
  await copyFile(join(root, '../models', file), join(assets, 'models', file));
await copyFile(
  join(root, '../models/doccornernet_lean.ort'),
  join(assets, 'ort/doccornernet_lean.ort'),
);
for (const file of await walk(join(root, '../licenses')))
  await copyFile(
    file,
    join(root, 'licenses', relative(join(root, '../licenses'), file).replaceAll(/[\\/]/g, '-')),
  );
for (const file of ['GCNet-MODEL-CARD.md', 'DocCornerNet-MODEL-CARD.md', 'Scanic-LICENSE.txt'])
  await copyFile(join(root, '../models', file), join(root, 'licenses', file));
const sources = {};
for (const path of (await walk(join(root, 'src'))).sort()) {
  const name = relative(root, path).replaceAll('\\', '/');
  if (
    [
      'src/sdk-assets.ts',
      'src/imaging/engines/docscan-assets.ts',
      'src/imaging/engines/scanic-ml-assets.ts',
    ].includes(name)
  )
    continue;
  sources[name] = sha(await readFile(path));
}
const artifactHashes = {};
for (const path of (await walk(assets)).sort())
  artifactHashes[relative(assets, path).replaceAll('\\', '/')] = sha(await readFile(path));
sources['vite.mjs'] = sha(await readFile(join(root, 'vite.mjs')));
const contract = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
const id = sha(
  JSON.stringify({
    sources,
    artifactHashes,
    dependencies: contract.dependencies,
    exports: contract.exports,
  }),
).slice(0, 12);
const base = `/docscan-sdk/${id}/`;
await writeFile(
  join(root, 'src/sdk-assets.ts'),
  `// Generated by the library build.\nexport const SDK_VERSION = '0.2.0-${id}';\nexport const SDK_ASSET_BASE = '${base}';\n`,
);
await writeFile(
  join(root, 'src/imaging/engines/docscan-assets.ts'),
  `import { SDK_ASSET_BASE, SDK_VERSION } from '../../sdk-assets';\nexport const DOCSCAN_WASM_BASE = SDK_ASSET_BASE + 'cpp/';\nexport const DOCSCAN_IMPLEMENTATION = 'docscan-sdk-' + SDK_VERSION;\n`,
);
await writeFile(
  join(root, 'src/imaging/engines/scanic-ml-assets.ts'),
  `import { SDK_ASSET_BASE } from '../../sdk-assets';\nexport const SCANIC_ORT_VERSION = '1.27.0';\nexport const SCANIC_ML_ASSET_BASE = SDK_ASSET_BASE + 'ort/';\n`,
);
await writeFile(
  join(root, 'assets.json'),
  JSON.stringify({ schema: 1, id, base, sources, assets: artifactHashes }, null, 2) + '\n',
);
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
pkg.version = `0.2.0-${id}`;
await writeFile(join(root, 'package.json'), JSON.stringify(pkg, null, 2) + '\n');
const vendor = join(web, 'vendor');
await mkdir(vendor, { recursive: true });
const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
const result = spawnSync(npm, ['pack', '--ignore-scripts', '--pack-destination', vendor], {
  cwd: root,
  encoding: 'utf8',
  shell: process.platform === 'win32',
});
if (result.status !== 0) throw new Error(result.stderr || 'SDK pack failed');
const archive = result.stdout.trim().split(/\r?\n/).at(-1);
console.log(
  JSON.stringify({
    id,
    archive: join(vendor, archive),
    dependency: `file:vendor/${archive}`,
  }),
);
